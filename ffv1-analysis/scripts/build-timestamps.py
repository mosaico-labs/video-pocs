#!/usr/bin/env python3
"""Associates each image of datasets/ImageSequence/001 with a capture time,
as an ideal camera records them.

The sequence was shot at 30000/1001 fps (29.97), so an ideal camera captures
frame i at START_NS + i * 1001/30000 s: every frame, ideal timing (the
`regular` scenario).

Writes one folder per batch size under ffv1-analysis/datasets/regular/:
batch_001 holds the first image, batch_002 the first two, ... up to all the
images. Each folder has a timestamps.csv with one row per image:

    image,timestamp_ns
    datasets/ImageSequence/001/000_8K.png,1767225600000000000

- image: the PNG's path, relative to the repository root.
- timestamp_ns: the capture time, in nanoseconds since the Unix epoch.

The times are deterministic, so running the script again gives the same
files. Run it from anywhere: ffv1-analysis/scripts/build-timestamps.py
"""

import csv
import shutil
from pathlib import Path

REPO_DIR = Path(__file__).resolve().parents[2]
IMAGES_DIR = REPO_DIR / "datasets" / "ImageSequence" / "001"
OUT_DIR = REPO_DIR / "ffv1-analysis" / "datasets" / "regular"

START_NS = 1_767_225_600_000_000_000  # 2026-01-01T00:00:00Z
FPS_NUM, FPS_DEN = 30000, 1001


def ideal_ns(index: int) -> int:
    # index * FPS_DEN / FPS_NUM seconds, rounded to the nearest nanosecond
    return START_NS + (index * FPS_DEN * 10**9 + FPS_NUM // 2) // FPS_NUM


def readme(rows) -> str:
    return f"""\
# regular: every frame, ideal timing

Capture times for the images of `datasets/ImageSequence/001/` ({len(rows)} PNG
frames, 8192x4320), as an ideal camera records them: every frame is
delivered, and frame *i* is captured exactly *i* × 1001/30000 s after the
first one, so frames are always {(ideal_ns(1) - START_NS) / 1e6:.1f} ms apart. This is how SEPE shot the
sequence: at 29.97 fps, exactly 30000/1001. These times fit a constant
frame rate, so `prepare` encodes them as a 30000/1001 video.

`batch_001/` holds the first image, `batch_002/` the first two, and so on up
to `batch_{len(rows):03d}/`, which holds all of them. Each folder has a
`timestamps.csv` with one row per image:

```
image,timestamp_ns
{rows[0][0]},{rows[0][1]}
```

- `image`: the PNG's path, relative to the repository root, in
  `datasets/ImageSequence/001/` (8192x4320 PNGs, not copied here).
- `timestamp_ns`: the capture time, in nanoseconds since the Unix epoch; the
  first capture is at 2026-01-01T00:00:00Z.

This folder is generated by `ffv1-analysis/scripts/build-timestamps.py`
(a few seconds, needs the PNGs: `scripts/build-datasets.sh images`); every
run writes the same files.
"""


def main() -> None:
    images = sorted(IMAGES_DIR.glob("*.png"))
    if not images:
        raise SystemExit(f"no PNG images in {IMAGES_DIR}: run scripts/build-datasets.sh images")
    rows = [(img.relative_to(REPO_DIR).as_posix(), ideal_ns(i)) for i, img in enumerate(images)]
    width = len(str(len(rows)))

    shutil.rmtree(OUT_DIR, ignore_errors=True)  # no stale batches from an earlier run
    for size in range(1, len(rows) + 1):
        batch_dir = OUT_DIR / f"batch_{size:0{width}d}"
        batch_dir.mkdir(parents=True)
        with open(batch_dir / "timestamps.csv", "w", newline="") as f:
            writer = csv.writer(f)
            writer.writerow(["image", "timestamp_ns"])
            writer.writerows(rows[:size])
    (OUT_DIR / "README.md").write_text(readme(rows))
    print(f"regular: {len(rows)} batches in {OUT_DIR}")


if __name__ == "__main__":
    main()
