#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = ["matplotlib>=3.9"]
# ///
"""Draws one chart per video comparing the video size with the size of the
.arrow file the server stored, from the CSV produced by flatten.py.

Usage: uv run per_video_charts.py [results dir]   (default: poc1/results)
Writes <results dir>/per-video/<dataset>/<resolution>/<codec>/<video>.png and
an index, <results dir>/per-video/README.md.
"""
import csv
import re
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.ticker import FuncFormatter  # noqa: E402

RESULTS = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent / "results"
OUT = RESULTS / "per-video"
MIB = 1024 * 1024
VIDEO_COLOR, ARROW_COLOR = "#898781", "#2a78d6"
INK, MUTED, GRID, AXIS = "#0b0b0b", "#52514e", "#e1e0d9", "#c3c2b7"


def slug(text: str) -> str:
    return re.sub(r"[^A-Za-z0-9.]+", "-", text).strip("-")


def chart(row: dict, path: Path) -> None:
    video, arrow = int(row["file_bytes"]), int(row["arrow_bytes"])
    extra = arrow - video
    fig, ax = plt.subplots(figsize=(6, 4), dpi=120, facecolor="white")
    bars = ax.bar([0, 1], [video / MIB, arrow / MIB], width=0.5, color=[VIDEO_COLOR, ARROW_COLOR], zorder=3)
    for bar, size in zip(bars, (video, arrow)):
        ax.text(bar.get_x() + bar.get_width() / 2, bar.get_height(), f"{size / MIB:,.2f} MiB\n{size:,} bytes",
                ha="center", va="bottom", fontsize=8.5, color=INK, linespacing=1.3)
    ax.set_xticks([0, 1], ["Video", ".arrow"])
    ax.set_ylim(0, arrow / MIB * 1.22)
    ax.yaxis.set_major_formatter(FuncFormatter(lambda v, _: f"{v:g}"))
    ax.set_ylabel("MiB", fontsize=9, color=MUTED)

    ax.set_title(row["file"], loc="left", fontsize=12, color=INK, fontweight="bold", pad=30)
    ax.text(0, 1.035, f"{row['source']} · {row['resolution']} · {row['codec']} · {int(row['chunks_received'])} chunks",
            transform=ax.transAxes, fontsize=8.5, color=MUTED, va="bottom")
    ax.text(1, -0.16, f".arrow is {extra:+,} bytes ({extra / 1024:+,.1f} KiB, {(arrow / video - 1) * 100:+.3f}%)",
            transform=ax.transAxes, fontsize=9, color=INK, ha="right", va="top")

    ax.grid(True, axis="y", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    for side in ("top", "right", "left"):
        ax.spines[side].set_visible(False)
    ax.spines["bottom"].set_color(AXIS)
    ax.tick_params(colors=MUTED, labelsize=9, length=0)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path)
    plt.close(fig)


rows = list(csv.DictReader((RESULTS / "videos.csv").open()))
rows.sort(key=lambda r: (r["source"], int(r["resolution_rank"]), r["codec"], r["file"]))

index = ["# Video and .arrow size per video\n",
         f"One chart per video ({len(rows)} in total), generated by `scripts/per_video_charts.py`.\n"]
section = None
for i, row in enumerate(rows, 1):
    rel = Path(slug(row["source"])) / row["resolution"] / slug(row["codec"]) / f"{Path(row['file']).stem}.png"
    chart(row, OUT / rel)
    group = f"{row['source']} · {row['resolution']} · {row['codec']}"
    if group != section:
        section = group
        index += [f"\n## {group}\n", "| Video | Video bytes | .arrow bytes | Difference | Chart |",
                  "|---|---:|---:|---:|---|"]
    video, arrow = int(row["file_bytes"]), int(row["arrow_bytes"])
    index.append(f"| `{row['file']}` | {video:,} | {arrow:,} | {arrow - video:+,} ({(arrow / video - 1) * 100:+.3f}%) "
                 f"| [chart]({rel.as_posix()}) |")
    if i % 100 == 0:
        print(f"{i}/{len(rows)}")

(OUT / "README.md").write_text("\n".join(index) + "\n")
print(f"{len(rows)} charts -> {OUT}")
